#!/usr/bin/env python3
#
# gen-sbox-entries.py -- generate Foundation_Spark.AES.Spec.Properties.SBox_Entries
# (issue #12), the case enumeration that proves SBox.cry's SBoxCorrect.
#
# For each byte b, it runs GF2.cry's pgcd's inner on [b, 1, 0, SBoxPolynomial,
# 0, 1], as shared/algebra/Polynomial/GF2.cry states it (pdiv by long
# division, pmult, and x ^. x' = drop (zext x ^ q ^* x') at type [9]), and
# writes one Lemma_Step per step of inner. The states are hints: gnatprove
# checks every step against the spec layer's GF2, so a wrong state here is
# an unproved check, not a wrong proof.
#
# Usage (from spark/):
#   python3 scripts/gen-sbox-entries.py src/aes/foundation_spark-aes-spec-properties-sbox_entries
# writes that path's .ads and .adb.

import sys

SBOX_POLYNOMIAL = 0x11B


def pmult(x, y):
    """pmult at [9] -> [9] -> [17]."""
    r = 0
    for i in range(9):
        if (x >> i) & 1:
            r ^= y << i
    return r


def pdiv(x, y):
    """pdiv at [9] -> [9] -> [9], by long division."""
    d = y.bit_length() - 1
    q = r = 0
    for n in range(9):
        t = (r << 1) | ((x >> (8 - n)) & 1)
        bit = 1 if t >= (1 << d) else 0
        if bit:
            t ^= y
        r = t
        q = (q << 1) | bit
    return q


def sub(x, x1, q):
    """x ^. x' = drop (zext x ^ q ^* x') at type [9]."""
    return (x ^ pmult(q, x1)) & 0x1FF


def trace(b):
    """The states of inner from [b, 1, 0, SBoxPolynomial, 0, 1]."""
    s = [b, 1, 0, SBOX_POLYNOMIAL, 0, 1]
    states = [s]
    while s[3] != 0:
        q = pdiv(s[0], s[3])
        s = [s[3], s[4], s[5],
             sub(s[0], s[3], q), sub(s[1], s[4], q), sub(s[2], s[5], q)]
        states.append(s)
    return states


def lit(s):
    return 'State (' + ', '.join('%d' % v for v in s) + ')'


def branch(b):
    t = trace(b)
    f = lit(t[-1])
    out = []
    for i in reversed(range(len(t) - 1)):
        out += ['            Lemma_Step',
                '              (%s,' % lit(t[i]),
                '               %s,' % lit(t[i + 1]),
                '               %s);' % f]
    out += ['            Lemma_Inner_Eq',
            '              ([GF2.Poly (B), 1, 0, SBox.SBoxPolynomial, 0, 1],',
            '               %s);' % lit(t[0]),
            '            pragma Assert',
            '              (GF2.Pgcd (B, SBox.SBoxPolynomial) (1) = %d);'
            % t[-1][1],
            '            pragma Assert (SBox.Affine (B) = SBox.SBox (B));']
    return out


SPEC_HEADER = '''\
--  SBox.cry's SBoxCorrect, entry by entry: affine b == SBox @ b for each
--  of the 256 bytes b, by evaluation. Lemma_SBox_Entry states one entry;
--  sixteen row lemmas, one per value of b / 16, each prove sixteen
--  entries, so that each is analyzed on its own.
--
--  For each byte, the body lists the states that GF2.cry's pgcd's inner
--  passes through computing inverse b SBoxPolynomial, one Lemma_Step per
--  step of inner, from the last back to the first. The provers check each
--  step, evaluating pdiv and pmult on constants, and then the affine
--  transformation of the inverse that the final state gives.
--
--  Generated by scripts/gen-sbox-entries.py. Do not edit by hand.

package Foundation_Spark.AES.Spec.Properties.SBox_Entries with
  SPARK_Mode,
  Pure,
  Ghost
is
'''

BODY_HEADER = '''\
--  Generated by scripts/gen-sbox-entries.py. Do not edit by hand.

package body Foundation_Spark.AES.Spec.Properties.SBox_Entries with
  SPARK_Mode
is

   function State (R, S, T, R1, S1, T1 : GF2.Poly) return GF2.Poly_State
   is ([R, S, T, R1, S1, T1]);
   --  The state [r, s, t, r', s', t'] of pgcd's inner, from its six
   --  polynomials.
   --  @param R The Cryptol's r.
   --  @param S The Cryptol's s.
   --  @param T The Cryptol's t.
   --  @param R1 The Cryptol's r'.
   --  @param S1 The Cryptol's s'.
   --  @param T1 The Cryptol's t'.
   --  @return [r, s, t, r', s', t'].
'''


def main(out):
    spec = [SPEC_HEADER]
    for r in range(16):
        spec.append('''\
   procedure Lemma_SBox_Row_%X (B : Types.Byte)
   with
     Pre  => B / 16 = %d,
     Post => SBox.Affine (B) = SBox.SBox (B);
   --  The entries 16#%X0# .. 16#%XF# of SBoxCorrect.
   --  @param B The byte.
''' % (r, r, r, r))
    spec.append('''\
   procedure Lemma_SBox_Entry (B : Types.Byte)
   with Post => SBox.Affine (B) = SBox.SBox (B);
   --  Entry B of SBoxCorrect: affine b == SBox @ b.
   --  @param B The byte.

end Foundation_Spark.AES.Spec.Properties.SBox_Entries;
''')
    with open(out + '.ads', 'w') as f:
        f.write('\n'.join(spec))

    body = [BODY_HEADER]
    for r in range(16):
        name = 'Lemma_SBox_Row_%X' % r
        rule = '   ' + '-' * (len(name) + 6)
        lines = [rule, '   -- %s --' % name, rule, '',
                 '   procedure %s (B : Types.Byte) is' % name,
                 '   begin', '      case B is']
        for b in range(16 * r, 16 * r + 16):
            lines.append('         when 16#%02X# =>' % b)
            lines += branch(b)
        lines += ['         when others =>', '            null;',
                  '      end case;', '   end %s;' % name, '']
        body.append('\n'.join(lines))
    lines = ['   ----------------------', '   -- Lemma_SBox_Entry --',
             '   ----------------------', '',
             '   procedure Lemma_SBox_Entry (B : Types.Byte) is', '   begin',
             '      case B / 16 is']
    for r in range(16):
        lines.append('         when %d => Lemma_SBox_Row_%X (B);' % (r, r))
    lines += ['         when others => null;', '      end case;',
              '   end Lemma_SBox_Entry;', '',
              'end Foundation_Spark.AES.Spec.Properties.SBox_Entries;', '']
    body.append('\n'.join(lines))
    with open(out + '.adb', 'w') as f:
        f.write('\n'.join(body))


if __name__ == '__main__':
    main(sys.argv[1])
