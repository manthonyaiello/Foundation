#!/usr/bin/env python3
#
# gen-sbox-entries.py -- generate Foundation_Spark.AES.Spec.SBox.SBox_Entries,
# the case enumeration that proves SBox.cry's SBoxCorrect.
#
# The unit is a child of SBox, not of Properties, so that its
# closure, and with it the slow proof's fingerprint, is only Types, GF2,
# GF28 and SBox: a change to KeyExpansion, Cipher or Main does not make it
# stale.
#
# For each byte b, it runs GF2.cry's pgcd's inner on [b, 1, 0, SBoxPolynomial,
# 0, 1], as shared/algebra/Polynomial/GF2.cry states it (pdiv by long
# division, pmult, and x ^. x' = drop (zext x ^ q ^* x') at type [9]), and
# writes one Lemma_Step per step of inner. The states are hints: gnatprove
# checks every step against the spec layer's GF2, so a wrong state here is
# an unproved check, not a wrong proof.
#
# The unit is split in two kinds of lemma per row of 16 bytes:
#   * Lemma_Inverse_Row_X evaluates inner, and states inverse b
#     SBoxPolynomial for each b of the row as a literal. It names nothing of
#     SBox but the constant SBoxPolynomial, so its proof context is GF2's;
#   * Lemma_SBox_Row_X takes those inverses and checks affine b == SBox @ b.
# Every goal's proof task carries the declarations its subprogram names.
# When one subprogram did both, each of the ~150 pgcd steps per row carried
# the 256-entry SBox aggregate and affine's definition, which no step uses:
# measured on rows 3 and C, the split cut gnatprove's wall-clock from 237 s
# to 73 s at -j6, its gnatwhy3 time from 369 s to 125 s and its prover time
# from 1350 s to 354 s.
#
# Usage (from spark/):
#   python3 scripts/gen-sbox-entries.py src/aes/foundation_spark-aes-spec-sbox-sbox_entries
# writes that path's .ads and .adb.

import sys

SBOX_POLYNOMIAL = 0x11B


def pmult(x, y):
    """pmult at [9] -> [9] -> [17]."""
    r = 0
    for i in range(9):
        if (x >> i) & 1:
            r ^= y << i
    return r


def pdiv(x, y):
    """pdiv at [9] -> [9] -> [9], by long division."""
    d = y.bit_length() - 1
    q = r = 0
    for n in range(9):
        t = (r << 1) | ((x >> (8 - n)) & 1)
        bit = 1 if t >= (1 << d) else 0
        if bit:
            t ^= y
        r = t
        q = (q << 1) | bit
    return q


def sub(x, x1, q):
    """x ^. x' = drop (zext x ^ q ^* x') at type [9]."""
    return (x ^ pmult(q, x1)) & 0x1FF


def trace(b):
    """The states of inner from [b, 1, 0, SBoxPolynomial, 0, 1]."""
    s = [b, 1, 0, SBOX_POLYNOMIAL, 0, 1]
    states = [s]
    while s[3] != 0:
        q = pdiv(s[0], s[3])
        s = [s[3], s[4], s[5],
             sub(s[0], s[3], q), sub(s[1], s[4], q), sub(s[2], s[5], q)]
        states.append(s)
    return states


def lit(s):
    return 'State (' + ', '.join('%d' % v for v in s) + ')'


def inverse(b):
    """inverse b SBoxPolynomial: the tail of u in inner's final state."""
    return trace(b)[-1][1] & 0xFF


def branch(b):
    t = trace(b)
    f = lit(t[-1])
    out = []
    for i in reversed(range(len(t) - 1)):
        out += ['            Lemma_Step',
                '              (%s,' % lit(t[i]),
                '               %s,' % lit(t[i + 1]),
                '               %s);' % f]
    out += ['            Lemma_Inner_Eq',
            '              ([GF2.Poly (B), 1, 0, SBoxPolynomial, 0, 1],',
            '               %s);' % lit(t[0]),
            '            pragma Assert',
            '              (GF2.Pgcd (B, SBoxPolynomial) (1) = %d);'
            % t[-1][1]]
    return out


SPEC_HEADER = '''\
--  SBox.cry's SBoxCorrect, entry by entry: affine b == SBox @ b for each
--  of the 256 bytes b, by evaluation. Lemma_SBox_Entry states one entry;
--  sixteen row lemmas, one per value of b / 16, each prove sixteen
--  entries, so that each is analyzed on its own.
--
--  Each row is two lemmas. Lemma_Inverse_Row_X states inverse b
--  SBoxPolynomial for the sixteen bytes of row X as literals. For each
--  byte, its body lists the states that GF2.cry's pgcd's inner passes
--  through, one Lemma_Step per step of inner, from the last back to the
--  first, and the provers check each step, evaluating pdiv and pmult on
--  constants. Lemma_SBox_Row_X then checks the affine transformation of
--  those inverses against the table. The inverse lemmas name nothing of
--  SBox but SBoxPolynomial, so that the goals of the steps, nearly all of
--  the unit's, do not carry the table and affine.
--
--  The unit is a child of SBox, so that what its proof depends on is SBox
--  and what SBox depends on (Types, GF2, GF28), and nothing else of the
--  spec layer. SBoxCorrect itself is stated in
--  Foundation_Spark.AES.Spec.Properties, with the other properties of
--  algorithms/AES, and proved there from Lemma_SBox_Entry.
--
--  Generated by scripts/gen-sbox-entries.py. Do not edit by hand.

with Interfaces;

package Foundation_Spark.AES.Spec.SBox.SBox_Entries with
  SPARK_Mode,
  Pure,
  Ghost
is

   use type Interfaces.Unsigned_16;
   use type GF2.Poly_State;

   procedure Lemma_Inner_Eq (A, B : GF2.Poly_State)
   with
     Pre                => GF2.Is_State (A) and then A = B,
     Post               => GF2.Inner (A) = GF2.Inner (B),
     Subprogram_Variant => (Decreases => A (3));
   --  GF2.cry's pgcd's inner maps equal states to equal states.
   --  @param A A state.
   --  @param B A state equal to A.

   procedure Lemma_Step (S, T, F : GF2.Poly_State)
   with
     Pre  => GF2.Is_State (S) and then S (3) /= 0
             and then GF2.Inner_Step (S) = T
             and then GF2.Is_State (T) and then GF2.Inner (T) = F,
     Post => GF2.Inner (S) = F;
   --  One step of pgcd's inner: when inner's step takes S to T, and inner
   --  ends in F from T, it ends in F from S.
   --  @param S A state whose r' is nonzero.
   --  @param T The state one step of inner after S.
   --  @param F The state inner ends in from T.
'''

BODY_HEADER = '''\
--  Generated by scripts/gen-sbox-entries.py. Do not edit by hand.
--
--  Slow proof: proved on demand (scripts/proof-slow.txt). Its cold proof is
--  too long for the default gate (README "Slow proofs").

package body Foundation_Spark.AES.Spec.SBox.SBox_Entries with
  SPARK_Mode
is

   --------------------
   -- Lemma_Inner_Eq --
   --------------------

   procedure Lemma_Inner_Eq (A, B : GF2.Poly_State) is
   begin
      if A (3) /= 0 then
         pragma Assert (GF2.Inner_Step (A) = GF2.Inner_Step (B));
         Lemma_Inner_Eq (GF2.Inner_Step (A), GF2.Inner_Step (B));
      end if;
   end Lemma_Inner_Eq;

   ----------------
   -- Lemma_Step --
   ----------------

   procedure Lemma_Step (S, T, F : GF2.Poly_State) is
   begin
      Lemma_Inner_Eq (GF2.Inner_Step (S), T);
      pragma Assert (GF2.Inner (GF2.Inner_Step (S)) = F);
   end Lemma_Step;

   function State (R, S, T, R1, S1, T1 : GF2.Poly) return GF2.Poly_State
   is ([R, S, T, R1, S1, T1]);
   --  The state [r, s, t, r', s', t'] of pgcd's inner, from its six
   --  polynomials.
   --  @param R The Cryptol's r.
   --  @param S The Cryptol's s.
   --  @param T The Cryptol's t.
   --  @param R1 The Cryptol's r'.
   --  @param S1 The Cryptol's s'.
   --  @param T1 The Cryptol's t'.
   --  @return [r, s, t, r', s', t'].
'''


def main(out):
    spec = [SPEC_HEADER]
    for r in range(16):
        alts = ',\n'.join('          when 16#%02X# => 16#%02X#' % (b, inverse(b))
                          for b in range(16 * r, 16 * r + 16))
        spec.append('''\
   procedure Lemma_Inverse_Row_%X (B : Types.Byte)
   with
     Pre  => B / 16 = %d,
     Post => GF2.Inverse (B, SBoxPolynomial) =
       (case B is
%s,
          when others => 0);
   --  inverse b SBoxPolynomial for the bytes 16#%X0# .. 16#%XF#, by
   --  evaluating GF2.cry's pgcd.
   --  @param B The byte.

   procedure Lemma_SBox_Row_%X (B : Types.Byte)
   with
     Pre  => B / 16 = %d,
     Post => Affine (B) = SBox (B);
   --  The entries 16#%X0# .. 16#%XF# of SBoxCorrect.
   --  @param B The byte.
''' % (r, r, alts, r, r, r, r, r, r))
    spec.append('''\
   procedure Lemma_SBox_Entry (B : Types.Byte)
   with Post => Affine (B) = SBox (B);
   --  Entry B of SBoxCorrect: affine b == SBox @ b.
   --  @param B The byte.

end Foundation_Spark.AES.Spec.SBox.SBox_Entries;
''')
    with open(out + '.ads', 'w') as f:
        f.write('\n'.join(spec))

    body = [BODY_HEADER]
    for r in range(16):
        name = 'Lemma_Inverse_Row_%X' % r
        rule = '   ' + '-' * (len(name) + 6)
        lines = [rule, '   -- %s --' % name, rule, '',
                 '   procedure %s (B : Types.Byte) is' % name,
                 '   begin', '      case B is']
        for b in range(16 * r, 16 * r + 16):
            lines.append('         when 16#%02X# =>' % b)
            lines += branch(b)
        lines += ['         when others =>', '            null;',
                  '      end case;', '   end %s;' % name, '']
        name = 'Lemma_SBox_Row_%X' % r
        rule = '   ' + '-' * (len(name) + 6)
        lines += [rule, '   -- %s --' % name, rule, '',
                  '   procedure %s (B : Types.Byte) is' % name,
                  '   begin', '      Lemma_Inverse_Row_%X (B);' % r,
                  '      case B is']
        for b in range(16 * r, 16 * r + 16):
            lines += ['         when 16#%02X# =>' % b,
                      '            pragma Assert (Affine (B) = SBox (B));']
        lines += ['         when others =>', '            null;',
                  '      end case;', '   end %s;' % name, '']
        body.append('\n'.join(lines))
    lines = ['   ----------------------', '   -- Lemma_SBox_Entry --',
             '   ----------------------', '',
             '   procedure Lemma_SBox_Entry (B : Types.Byte) is', '   begin',
             '      case B / 16 is']
    for r in range(16):
        lines.append('         when %d => Lemma_SBox_Row_%X (B);' % (r, r))
    lines += ['         when others => null;', '      end case;',
              '   end Lemma_SBox_Entry;', '',
              'end Foundation_Spark.AES.Spec.SBox.SBox_Entries;', '']
    body.append('\n'.join(lines))
    with open(out + '.adb', 'w') as f:
        f.write('\n'.join(body))


if __name__ == '__main__':
    main(sys.argv[1])
